-- Interactive lessons (pklesson.lua) on the fixture study.
local Chess = require("chess")
local PkLesson = require("pklesson")
local PkStudy = require("pkstudy")

local FIXTURE = (PK_REPO_ROOT or ".") .. "/plugin/tests/fixtures/study.pgn"

local function lesson(chapter, student, opts)
    local s = assert(PkStudy.open(FIXTURE))
    local c = assert(s:cursor(chapter, Chess:new()))
    return PkLesson.new(c, student, opts), c
end

return {
    { "gamebook: good moves, opponent replies, end", function(t)
        local l, c = lesson(2, "w", { variations_are_mistakes = true })
        t.eq(l:start(), "play", "white starts: student to move")
        local verdict = l:onStudentMove("d2", "d8")
        t.eq(verdict, "good", "Qxd8+ is the main line")
        t.eq(l.state, "reply", "opponent to reply")
        local reply = l:opponentReply()
        t.eq(reply.san, "Qxd8", "opponent main-line reply")
        t.eq(l.state, "play", "student again")
        t.eq(l:onStudentMove("d1", "d8"), "end", "mate ends the lesson")
        t.ok(l:isOver(), "over"); t.eq(l.mistakes, 0, "no mistakes")
        t.ok(c.game.in_checkmate(), "final position")
    end },
    { "gamebook: variation move is a known mistake with its comment", function(t)
        local l, c = lesson(2, "w", { variations_are_mistakes = true })
        l:start()
        local fen = c.game.fen()
        local verdict, node = l:onStudentMove("f4", "e5")
        t.eq(verdict, "bad", "fxe5 is in the study as a mistake")
        t.ok(node.comment:find("misses the mate"), "explanation available")
        t.eq(c.game.fen(), fen, "position unchanged")
        t.eq(l.mistakes, 1, "mistake counted")
        t.eq(l:onStudentMove("a2", "a3"), "wrong", "move not in the study")
        t.eq(l.mistakes, 2, "second mistake")
        t.eq(l.state, "play", "still the student's turn")
    end },
    { "hint and solution", function(t)
        local l = lesson(2, "w")
        l:start()
        t.eq(l:hint(), "d2", "hint square")
        t.ok(l.used_help, "help used")
        local verdict, node = l:solution()
        t.eq(verdict, "good", "solution plays the main move"); t.eq(node.san, "Qxd8+", "node")
    end },
    { "student playing the second side: the caller paces the opponent's first move", function(t)
        local l, c = lesson(1, "b")
        t.eq(l:start(), "reply", "opponent to move first")
        t.eq(c.node, c.root, "nothing played yet (intro readable)")
        t.eq(l:opponentReply().san, "e4", "1. e4 for White")
        t.eq(l.state, "play", "student's turn")
        t.eq(l:expected().san, "e5", "student must find e5")
    end },
    { "illegal moves in the PGN put the lesson in an error state", function(t)
        local game = Chess:new()
        local bad_reply = PkStudy.fromText('[Event "x"]\n\n1. e4 Ke3 2. d4 *\n')
        local l = PkLesson.new(assert(bad_reply:cursor(1, game)), "w")
        l:start()
        t.eq(l:onStudentMove("e2", "e4"), "good", "student move")
        t.eq(l.state, "error", "opponent's main-line move is illegal")
        t.ok(l.error:find("Ke3"), l.error)
        t.eq(l:opponentReply(), nil, "no reply in error state")
        local bad_expected = PkStudy.fromText('[Event "y"]\n\n1. Ke3 *\n')
        local l2 = PkLesson.new(assert(bad_expected:cursor(1, game)), "w")
        t.eq(l2:start(), "error", "expected move illegal")
        t.eq(l2:hint(), nil, "no hint"); t.eq(l2:solution(), nil, "no solution")
    end },
    { "promotion in a lesson: the piece matters", function(t)
        local l = lesson(5, "w")
        l:start()
        t.eq(l:onStudentMove("e1", "c1"), "good", "O-O-O")
        l:opponentReply()
        t.eq(l:onStudentMove("b7", "b8", "n"), "wrong", "underpromotion is not the move")
        t.eq(l:onStudentMove("b7", "b8", "q"), "good", "b8=Q")
    end },
    { "solution to the end marks help", function(t)
        local l = lesson(2, "w", { variations_are_mistakes = true })
        l:start()
        l:solution(); l:opponentReply()
        local verdict = l:solution()
        t.eq(verdict, "end", "solution finishes the lesson")
        t.ok(l.used_help and l.mistakes == 0, "help used, no mistakes")
    end },
    { "training a normal chapter: variations are sidelines, not mistakes", function(t)
        local l = lesson(1, "w", { variations_are_mistakes = false })
        l:start()
        l:onStudentMove("e2", "e4"); l:opponentReply()
        l:onStudentMove("g1", "f3"); l:opponentReply()
        local verdict = l:onStudentMove("f1", "b5")
        t.eq(verdict, "sideline", "Bb5 is a variation in this chapter")
        t.eq(l.mistakes, 0, "not counted as a mistake")
        t.eq(l:onStudentMove("f1", "c4"), "good", "main line Bc4")
    end },
}
